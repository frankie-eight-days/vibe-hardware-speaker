#!/usr/bin/env python3
"""Regenerate the generated appendix .tex files from the project's source files.

Since revision 0.3 the write-up summarises the specs and links to them in the
repository instead of reproducing them, so only the BOM table is generated by
default. The pandoc spec conversion is kept: pass --specs to regenerate
generated/spec_*.tex (not included in main.tex).

Run from anywhere:  python3 docs/writeup/convert_sources.py
Inputs (read-only):  docs/requirements.md, docs/spec_power.md,
                     docs/spec_signal.md, docs/spec_ui_board.md,
                     hw/mainboard/out/speaker_main_bom.csv
Outputs:             docs/writeup/generated/*.tex

Markdown -> LaTeX goes through pandoc (GFM reader, no auto identifiers so the
labels of different specs cannot collide). Headings are shifted down one level
so each spec's title becomes a \\subsection inside its appendix section.
\\texttt runs (file names, footprint names) get break points after '_', '/',
':' so long identifiers do not run into the margin.
"""
import csv
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
GEN = os.path.join(HERE, "generated")

PANDOC = shutil.which("pandoc") or "/opt/homebrew/bin/pandoc"

SPECS = [
    ("docs/requirements.md", "requirements.tex"),
    ("docs/spec_power.md", "spec_power.tex"),
    ("docs/spec_signal.md", "spec_signal.tex"),
    ("docs/spec_ui_board.md", "spec_ui_board.tex"),
]

TT = re.compile(r"\\texttt\{((?:[^{}]|\{\})*)\}")


def breakable_tt(m):
    body = m.group(1)
    body = body.replace(r"\_", r"\_\allowbreak{}")
    body = body.replace("/", r"/\allowbreak{}")
    body = body.replace(":", r":\allowbreak{}")
    return r"\texttt{" + body + "}"


def convert_md(src, dst):
    cmd = [
        PANDOC,
        "-f", "markdown-auto_identifiers+lists_without_preceding_blankline-tex_math_dollars-raw_tex",
        "-t", "latex",
        "--syntax-highlighting=none",
        "--shift-heading-level-by=1",
        "--wrap=preserve",
        os.path.join(ROOT, src),
    ]
    tex = subprocess.run(cmd, check=True, capture_output=True, text=True).stdout
    tex = TT.sub(breakable_tt, tex)
    # Identifiers outside \texttt (symbol names such as Connector_Generic:Conn_01x02
    # in table cells): allow breaks after '_' and after ':' between letters.
    tex = re.sub(r"\\_(?!\\allowbreak)", r"\\_\\allowbreak{}", tex)
    tex = re.sub(r"(?<=[A-Za-z0-9]):(?=[A-Za-z_])", r":\\allowbreak{}", tex)
    # Verbatim blocks (ASCII diagrams) are wider than the text block: shrink them.
    tex = tex.replace(r"\begin{verbatim}", "{\\scriptsize\n\\begin{verbatim}")
    tex = tex.replace(r"\end{verbatim}", "\\end{verbatim}\n}")
    header = (
        "%% GENERATED by convert_sources.py from %s. Do not edit by hand.\n" % src
    )
    with open(os.path.join(GEN, dst), "w", encoding="utf-8") as f:
        f.write(header + tex)


def esc(s):
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
           "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
           "^": r"\textasciicircum{}"}
    return "".join(rep.get(c, c) for c in s)


def bom():
    src = os.path.join(ROOT, "hw/mainboard/out/speaker_main_bom.csv")
    with open(src, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    total = sum(int(r["Qty"]) for r in rows)
    lines = [
        "% GENERATED by convert_sources.py from hw/mainboard/out/speaker_main_bom.csv.",
        "{\\scriptsize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{0.25\\linewidth}"
        ">{\\raggedright\\arraybackslash}p{0.17\\linewidth}"
        ">{\\raggedright\\arraybackslash}p{0.36\\linewidth}"
        "l l r@{}}",
        "\\caption{Main-board bill of materials as exported from the schematic "
        "(%d lines, %d parts). Rows marked DNP carry the \\texttt{DNP} property; "
        "the KiCad DNP attribute itself is not yet set (see "
        "\\cref{sec:schematic}).}\\label{tab:bom}\\\\" % (len(rows), total),
        "\\toprule Designator & Value & Footprint & LCSC & DNP & Qty\\\\ \\midrule",
        "\\endfirsthead",
        "\\toprule Designator & Value & Footprint & LCSC & DNP & Qty\\\\ \\midrule",
        "\\endhead",
        "\\bottomrule",
        "\\endlastfoot",
    ]
    for r in rows:
        des = esc(r["Designator"]).replace(",", ", ")
        fp = esc(r["Footprint"]).replace(r"\_", r"\_\allowbreak{}").replace(":", r":\allowbreak{}")
        lines.append("%s & %s & \\texttt{%s} & %s & %s & %s\\\\" % (
            des, esc(r["Value"]), fp, esc(r["LCSC"]) or "---",
            esc(r["DNP"]), esc(r["Qty"])))
    lines += ["\\end{longtable}", "}"]
    with open(os.path.join(GEN, "bom.tex"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return len(rows), total


def main():
    os.makedirs(GEN, exist_ok=True)
    if "--specs" in sys.argv:
        for src, dst in SPECS:
            convert_md(src, dst)
            print("converted", src, "->", os.path.join("generated", dst))
    n, total = bom()
    print("BOM: %d lines, %d parts -> generated/bom.tex" % (n, total))


if __name__ == "__main__":
    sys.exit(main())
